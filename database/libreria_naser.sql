-- ============================================================
-- Librería NaSer - Sistema transaccional (EDI 3)
-- Crea una base NUEVA llamada libreria_naser. No toca otras bases.
-- Datos de stock y ventas: inventados para pruebas.
-- ============================================================

CREATE DATABASE IF NOT EXISTS libreria_naser
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE libreria_naser;

CREATE TABLE usuarios (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  clave VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE rubros (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE productos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(150) NOT NULL,
  rubro_id INT NOT NULL,
  precio_sin_iva DECIMAL(12,2) NOT NULL,
  precio_con_iva DECIMAL(12,2) NOT NULL,
  stock INT NOT NULL DEFAULT 0,
  stock_minimo INT NOT NULL DEFAULT 0,
  FOREIGN KEY (rubro_id) REFERENCES rubros(id)
) ENGINE=InnoDB;

CREATE TABLE ventas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  fecha DATETIME NOT NULL,
  total DECIMAL(12,2) NOT NULL,
  usuario_id INT NOT NULL,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
) ENGINE=InnoDB;

CREATE TABLE detalle_venta (
  id INT AUTO_INCREMENT PRIMARY KEY,
  venta_id INT NOT NULL,
  producto_id INT NOT NULL,
  cantidad INT NOT NULL,
  precio_unitario DECIMAL(12,2) NOT NULL,
  FOREIGN KEY (venta_id) REFERENCES ventas(id),
  FOREIGN KEY (producto_id) REFERENCES productos(id)
) ENGINE=InnoDB;

